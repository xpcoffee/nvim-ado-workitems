-- The view layout (RFC 0001 R4.2, RFC 0003 C6): one column of stacked
-- windows, the area view on top and the item buffer beneath it, reused on
-- later selections.
local views = require("tests.support.views")
local key, cursor_to = views.key, views.cursor_to

local function area(path)
  require("ado").area_view(path)
  return vim.api.nvim_get_current_win()
end

test("C6.3 selecting an item in the area view opens the list and the item buffer; the next selection reuses both", function()
  views.fresh()
  local area_win = area("P/Team/A")
  local area_buf = vim.api.nvim_get_current_buf()
  cursor_to("Fix login")
  key("<CR>")
  eq(#vim.api.nvim_list_wins(), 2)
  local panel = vim.api.nvim_get_current_win()
  eq(views.buf_name(panel), "ado://item/103", "the cursor is in the item buffer")
  eq(vim.api.nvim_win_get_buf(area_win), area_buf)
  local order = vim.fn.winlayout()
  eq(order[1], "col")
  eq({ order[2][1][2], order[2][2][2] }, { area_win, panel })

  vim.api.nvim_set_current_win(area_win)
  cursor_to("Write API")
  key("<CR>")
  eq(#vim.api.nvim_list_wins(), 2)
  eq(vim.api.nvim_get_current_win(), panel)
  eq(views.buf_name(panel), "ado://item/101")
end)

test("C6.2 with the list open the item window has two thirds of the column; alone it has all of it", function()
  local env = views.fresh()
  local area_win = area("P/Team/A")
  cursor_to("Fix login")
  key("<CR>")
  local panel = vim.api.nvim_get_current_win()
  local list_h, item_h = vim.api.nvim_win_get_height(area_win), vim.api.nvim_win_get_height(panel)
  local total = list_h + item_h
  eq(item_h, math.floor(total * 2 / 3 + 0.5))
  require("ado").toggle_area_view()
  eq(env.layout.window("list"), nil)
  eq(#vim.api.nvim_list_wins(), 1)
  ok(vim.api.nvim_win_get_height(panel) >= total, "the item window takes the column")
  require("ado").toggle_area_view()
  eq(vim.api.nvim_win_get_height(env.layout.window("item")), item_h, "back to two thirds")
end)

test("A0001-4 [h in the panel returns to the area location, with its filters, in the area window", function()
  local env = views.fresh()
  local area_win = area("P/Team/A")
  env.area_view.open(require("ado.core.location").with_filters(env.area_view.state(0).location, { assignee = "@Me" }))
  cursor_to("Fix login")
  key("<CR>")
  key("[h")
  eq(vim.api.nvim_get_current_win(), area_win)
  eq(env.area_view.state(0).location.filters.assignee, "@Me")
  key("]h")
  eq(views.buf_name(), "ado://item/103")
end)

test("a window the user put another buffer in is not reused", function()
  local env = views.fresh()
  local area_win = area("P/Team/A")
  cursor_to("Fix login")
  key("<CR>")
  local panel = vim.api.nvim_get_current_win()
  vim.cmd("enew")
  vim.api.nvim_set_current_win(area_win)
  cursor_to("Write API")
  key("<CR>")
  eq(#vim.api.nvim_list_wins(), 3)
  ok(vim.api.nvim_get_current_win() ~= panel)
  eq(views.buf_name(), "ado://item/101")
  eq(env.layout.window("item"), vim.api.nvim_get_current_win())
end)

test("toggling the area view closes it, then reopens the last area in its place on top", function()
  local env = views.fresh()
  area("P/Team/A")
  cursor_to("Fix login")
  key("<CR>")
  local panel = vim.api.nvim_get_current_win()
  require("ado").toggle_area_view()
  eq(env.layout.window("list"), nil)
  eq(#vim.api.nvim_list_wins(), 1)
  require("ado").toggle_area_view()
  local area_win = env.layout.window("list")
  ok(area_win, "the area view is back")
  eq(views.buf_name(area_win), "ado://area/P/Team/A?state=open&type=&assignee=&tag=&sub=0")
  eq(vim.fn.winlayout()[2][1][2], area_win, "on top")
  eq(env.layout.window("item"), panel)
end)

test("toggling the item view closes it, then reopens the last item", function()
  local env = views.fresh()
  area("P/Team/A")
  cursor_to("Fix login")
  key("<CR>")
  require("ado").toggle_item_view()
  eq(env.layout.window("item"), nil)
  require("ado").toggle_item_view()
  eq(views.buf_name(env.layout.window("item")), "ado://item/103")
  ok(env.layout.window("list"), "the list stays")
end)

test("toggling with nothing shown before falls back to asking", function()
  views.fresh()
  local asked
  local input = vim.ui.input
  vim.ui.input = function(opts) asked = opts.prompt end
  require("ado").toggle_item_view()
  vim.ui.input = input
  eq(asked, "Work item ID: ")
end)
