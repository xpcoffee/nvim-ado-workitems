-- The item view buffer on the fake transport: rows, labels, navigation and
-- history, the all-states toggle, preview, the area row, the detail
-- buffer's <leader>wi and the browser URL.
local views = require("tests.support.views")
local key, parsed, cursor_to = views.key, views.parsed, views.cursor_to

local function open(id)
  require("ado").item_view(id)
  return vim.api.nvim_get_current_buf()
end

test("item_view(id) opens ado://item/<id> in a window beneath the current one, rows in R3.1 order", function()
  local env = views.fresh()
  local first = vim.api.nvim_get_current_win()
  local buf = open(100)
  eq(vim.api.nvim_buf_get_name(buf), "ado://item/100")
  eq(vim.bo[buf].filetype, "adoitemview")
  eq(vim.bo[buf].modifiable, true)
  eq(#vim.api.nvim_list_wins(), 2)
  ok(vim.api.nvim_get_current_win() ~= first)
  eq(vim.fn.winlayout()[1], "col")
  eq(parsed(buf), { "Checkout story", "Parent: none", "P\\Team\\A", "Children: 2", "Write API", "Add tests",
    "Related: 1", "Payments story" })
  eq(vim.wo.winbar, "#100 User Story  ·  children and links: open only (<leader>wt for all)"
    .. "%=%#AdoCount#2 children · 1 linked%*")
  local labels = vim.api.nvim_buf_get_extmarks(buf, vim.api.nvim_get_namespaces().ado_view_labels, 0, -1,
    { details = true })
  eq(#labels, 1)
  eq(labels[1][4].virt_text[1][1], "this item")
  eq(#env.fake.calls, 3, "get_work_item, query, catalog")
end)

test("the parent row is labelled and shows a finished parent", function()
  views.fresh()
  local buf = open(107)
  eq(parsed(buf)[2], "Payments story")
  local labels = vim.api.nvim_buf_get_extmarks(buf, vim.api.nvim_get_namespaces().ado_view_labels, 0, -1,
    { details = true })
  eq(labels[2][2], 5, "after the item and its 4 field lines")
  eq(labels[2][4].virt_text[1][1], "parent")
end)

test("<CR> on a child navigates the panel; [h and ]h walk back and forward without reloading", function()
  local env = views.fresh()
  open(100)
  local panel = vim.api.nvim_get_current_win()
  cursor_to("Add tests")
  key("<CR>")
  eq(vim.api.nvim_get_current_win(), panel)
  eq(views.buf_name(), "ado://item/102")
  eq(parsed(0)[2], "Checkout story", "the parent row")
  local calls = #env.fake.calls
  key("[h")
  eq(views.buf_name(), "ado://item/100")
  key("]h")
  eq(views.buf_name(), "ado://item/102")
  eq(#env.fake.calls, calls)
  eq(#vim.api.nvim_list_wins(), 2, "no detail split was made")
end)

test("<leader>wt shows a finished child with no call, and [h returns to open only", function()
  local env = views.fresh()
  open(105)
  eq(parsed(0), { "Payments story", "Parent: none", "P\\Team\\B", "Children: 0 open of 1", "Related: 1",
    "Checkout story" })
  local calls = #env.fake.calls
  key("<leader>wt")
  eq(parsed(0), { "Payments story", "Parent: none", "P\\Team\\B", "Children: 1", "Refund flow", "Related: 1",
    "Checkout story" })
  ok(vim.wo.winbar:find("all states", 1, true), vim.wo.winbar)
  eq(env.item_view.state(0).location.all, true)
  key("[h")
  eq(parsed(0)[4], "Children: 0 open of 1")
  eq(#env.fake.calls, calls)
end)

test("R4.3 moving the cursor in the item view calls nothing and leaves the detail split alone", function()
  local env = views.fresh()
  open(100)
  cursor_to("Write API")
  key("K")
  local detail = env.layout.window("detail")
  local calls = #env.fake.calls
  for line = 1, vim.api.nvim_buf_line_count(0) do vim.api.nvim_win_set_cursor(0, { line, 0 }) end
  key("j")
  eq(#env.fake.calls, calls)
  eq(views.buf_name(detail), "ado://101")
end)

test("K previews in a detail split and keeps the cursor; gd moves to the detail buffer", function()
  local env = views.fresh()
  open(100)
  local panel = vim.api.nvim_get_current_win()
  cursor_to("Write API")
  key("K")
  eq(vim.api.nvim_get_current_win(), panel)
  local detail = env.layout.window("detail")
  ok(detail, "a detail split exists")
  eq(views.buf_name(detail), "ado://101")
  eq(vim.fn.win_screenpos(detail)[1] > vim.fn.win_screenpos(panel)[1], true, "the detail is beneath the panel")
  cursor_to("Add tests")
  key("K")
  eq(env.layout.window("detail"), detail, "the split is reused")
  eq(views.buf_name(detail), "ado://102")
  cursor_to("Payments story")
  key("gd")
  eq(vim.api.nvim_get_current_win(), detail)
  eq(views.buf_name(), "ado://105")
end)

test("<CR> on a link keeps an open detail split on the selected item", function()
  local env = views.fresh()
  open(100)
  cursor_to("Write API")
  key("K")
  cursor_to("Payments story")
  key("<CR>")
  eq(views.buf_name(), "ado://item/105")
  eq(views.buf_name(env.layout.window("detail")), "ado://105")
end)

test("A0001-5 <CR> on the area row lands in the area view of that path with default filters", function()
  local env = views.fresh({ area_filters = { state = "open", assignee = "@Me" } })
  open(102)
  cursor_to("P\\Team\\A")
  key("<CR>")
  eq(views.buf_name(), "ado://area/P/Team/A?state=open&type=&assignee=@Me&tag=&sub=0")
  eq(views.buf_name(env.layout.window("item")), "ado://item/102", "the panel stays")
  key("[h")
  eq(views.buf_name(), "ado://item/102")
end)

test("<leader>wi in a detail buffer opens the item view beside it", function()
  local env = views.fresh()
  require("ado").open(101)
  local detail = vim.api.nvim_get_current_win()
  key("<leader>wi")
  eq(views.buf_name(), "ado://item/101")
  eq(env.layout.window("detail"), detail)
  cursor_to("Checkout story")
  key("K")
  eq(views.buf_name(detail), "ado://100", "the detail buffer's window is the detail split")
  eq(#vim.api.nvim_list_wins(), 2)
end)

test("item_view() with no ID asks for one", function()
  views.fresh()
  vim.ui.input = function(o, answer)
    eq(o.prompt, "Work item ID: ")
    answer("103")
  end
  require("ado").item_view()
  eq(views.buf_name(), "ado://item/103")
end)

test("<leader>wb opens the item under the cursor, else the view's item", function()
  local env = views.fresh()
  open(100)
  cursor_to("Write API")
  key("<leader>wb")
  cursor_to("Children: 2")
  key("<leader>wb")
  eq(env.urls, { "https://dev.azure.com/test-org/_workitems/edit/101",
    "https://dev.azure.com/test-org/_workitems/edit/100" })
end)

test("<leader>wr reloads with 2 calls and shows the change", function()
  local env = views.fresh()
  open(100)
  env.fake:edit_remotely(101, { ["System.Title"] = "Write the API" })
  local calls = #env.fake.calls
  key("<leader>wr")
  eq(#env.fake.calls, calls + 2)
  eq(parsed(0)[5], "Write the API")
end)

test("a failed load says so in the window bar", function()
  local env = views.fresh()
  env.fake:fail_on("get_work_item", 1)
  open(100)
  ok(vim.wo.winbar:find("load failed", 1, true), vim.wo.winbar)
  eq(env.item_view.state(0).view, nil)
end)

test(":w in an item view saves nothing", function()
  local env = views.fresh()
  open(100)
  vim.cmd("write")
  vim.wait(20)
  eq(#env.fake.writes, 0)
end)

test("the viewed item shows its fields on their own lines beneath its title", function()
  views.fresh()
  local buf = open(107)
  local shown = views.shown(buf)
  ok(shown[2]:match("^type: "), shown[2])
  ok(shown[3]:match("^state: "), shown[3])
  ok(shown[4]:match("^assignee:"), shown[4])
  ok(shown[5]:match("^tags:"), shown[5])
  eq(shown[6], "Payments story")
end)
