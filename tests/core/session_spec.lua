local Fake = require("tests.support.fake_transport")
local query = require("ado.core.query")
local seed = require("tests.fixtures.seed")
local session = require("ado.core.session")

local function new(opts)
  local fake = Fake.new(seed)
  opts = opts or {}
  opts.transport = fake
  opts.org = opts.org or "test-org"
  return session.new(opts), fake
end

test("new refuses an incomplete transport", function()
  fails(function() session.new({ transport = {} }) end, "transport is missing operations")
end)

test("query sends WIQL, spec and project and returns normalised items", function()
  local s, fake = new({ project = "P" })
  async(fake, function(done)
    s:query(query.my_items(), function(err, items)
      eq(err, nil)
      eq(items[1].id, 112)
      eq(items[1].url, "https://dev.azure.com/test-org/_workitems/edit/112")
      done()
    end)
  end)
  eq(fake.calls[1].params.project, "P")
  ok(fake.calls[1].params.wiql:find("@Me", 1, true))
end)

test("query caps results at query_top", function()
  local s = new({ query_top = 2 })
  s:query(query.my_items(), function(_, items) eq(#items, 2) end)
end)

test("get returns the normalised item", function()
  local s = new()
  s:get(101, function(err, item)
    eq(err, nil)
    eq(item.title, "Write API")
  end)
end)

test("a catalog load for one project is not served to another, even in flight", function()
  local s, fake = new({ project = "P" })
  fake.mode = "deferred"
  local first, second
  s:catalog("P", function(_, c) first = c end)
  s:set_project("Q")
  s:catalog(s:default_project(), function(_, c) second = c end)
  fake:flush()
  ok(first ~= nil and second ~= nil, "both loads finish")
  ok(first ~= second, "Q is served its own catalog, not P's")
  eq(fake.calls[1].params.project, "P")
  eq(fake.calls[2].params.project, "Q")
  eq(#fake.calls, 2)
end)

test("update_if_unchanged writes when the rev matches", function()
  local s, fake = new()
  fake.mode = "deferred"
  async(fake, function(done)
    s:get(101, function(_, item)
      s:update_if_unchanged(item, { title = "Write the API" }, function(err, updated)
        eq(err, nil)
        eq(updated.title, "Write the API")
        eq(updated.rev, 2)
        done()
      end)
    end)
  end)
  eq(#fake.writes, 1)
  eq(fake.writes[1].params, { id = 101, fields = { ["System.Title"] = "Write the API" } })
end)

test("update_if_unchanged refuses with a conflict and no write after a remote edit", function()
  local s, fake = new()
  local item
  s:get(101, function(_, it) item = it end)
  fake:edit_remotely(101, { ["System.State"] = "Doing" })
  s:update_if_unchanged(item, { title = "Mine" }, function(err)
    eq(err.kind, "conflict")
    eq(err.expected_rev, 1)
    eq(err.actual_rev, 2)
  end)
  eq(#fake.writes, 0)
end)

test("add_comment returns the updated item", function()
  local s, fake = new()
  s:add_comment(103, "looking", function(err, item)
    eq(err, nil)
    eq(item.rev, 2)
  end)
  eq(fake.comments[103], { "looking" })
end)

test("states come from the catalog, loaded once for every type", function()
  local s, fake = new({ project = "P" })
  for _, t in ipairs({ "Task", "Bug", "Task" }) do
    s:states(t, nil, function(err, names)
      eq(err, nil)
      ok(#names > 0)
    end)
  end
  s:states("Task", nil, function(_, names) eq(names, { "To Do", "Doing", "Done", "Discarded" }) end)
  eq(#fake.calls, 1)
  eq(fake.calls[1], { op = "work_item_types", params = { project = "P" } })
end)

test("states of a type missing from the catalog is not_found", function()
  local s = new({ project = "P" })
  s:states("Epic", nil, function(err) eq(err.kind, "not_found") end)
end)

test("a transport error reaches the caller unchanged", function()
  local s, fake = new()
  fake:fail_on("get_work_item", 1, { kind = "auth", message = "expired" })
  s:get(101, function(err, item)
    eq(err, { kind = "auth", message = "expired" })
    eq(item, nil)
  end)
end)

test("list_projects and set_project", function()
  local s = new()
  s:list_projects(function(_, names) eq(names, { "P" }) end)
  s:set_project("P")
  eq(s.project, "P")
end)
