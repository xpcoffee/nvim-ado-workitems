local history = require("ado.core.history")
local location = require("ado.core.location")

local A, B, C = location.area("P\\A"), location.area("P\\B"), location.area("P\\C")

test("back and forward walk the visited locations", function()
  local h = history.new()
  h:visit(A)
  h:visit(B)
  h:visit(C)
  eq(h:back(), B)
  eq(h:back(), A)
  eq(h:back(), nil)
  eq(h:current(), A)
  eq(h:forward(), B)
  eq(h:forward(), C)
  eq(h:forward(), nil)
end)

test("a new navigation after going back clears forward", function()
  local h = history.new()
  h:visit(A)
  h:visit(B)
  h:back()
  h:visit(C)
  eq(h:forward(), nil)
  eq(h:back(), A)
end)

test("visiting the current location again adds no entry", function()
  local h = history.new()
  h:visit(A)
  h:visit(location.area("P/A"))
  eq(#h.entries, 1)
end)
